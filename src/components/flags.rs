//! 国旗：ISO 3166-1 alpha-2 两位代码到 Twemoji 旗帜图片的对照表。
//!
//! 不走字体是有原因的：GPUI 在 Windows 上把 emoji 交给 DirectWrite 的
//! COLR 彩色字形，而彩色字体（Twemoji、Segoe UI Emoji）的旗帜基字形都没有
//! 轮廓，光栅化边界为零，什么都画不出来；系统字体里区域指示符也只是两个
//! 字母。旗帜直接画成图片最稳。
//!
//! 图形来自 Twemoji（CC-BY 4.0），随仓库保存，运行时不联网。

use std::collections::HashMap;
use std::sync::{Arc, Mutex, OnceLock};

use gpui_kit::*;

/// `code` 那面旗，解码成 GPUI 能画的图后缓存复用。代码未知或解码失败时为
/// `None`。
pub fn flag_image(code: &str) -> Option<Arc<RenderImage>> {
    static CACHE: OnceLock<Mutex<HashMap<String, Option<Arc<RenderImage>>>>> = OnceLock::new();
    let cache = CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    if let Some(cached) = cache.lock().ok()?.get(code) {
        return cached.clone();
    }
    let decoded = flag_png(code).and_then(decode);
    if let Ok(mut cache) = cache.lock() {
        cache.insert(code.to_string(), decoded.clone());
    }
    decoded
}

/// PNG 解成 BGRA 帧：GPUI 的 `RenderImage` 按 BGRA 解读字节。
fn decode(data: &[u8]) -> Option<Arc<RenderImage>> {
    let image = image::load_from_memory(data).ok()?.to_rgba8();
    let (width, height) = image.dimensions();
    let mut frame = image::RgbaImage::from_raw(width, height, image.into_raw())?;
    for pixel in frame.pixels_mut() {
        pixel.0.swap(0, 2);
    }
    Some(Arc::new(RenderImage::new(vec![image::Frame::new(frame)])))
}

